    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
        String appDir = ConfigService.loadConfig().getProperty("app.dir");
        Path root = Paths.get(appDir, "Repo");

        String RepoName = RepoNameTxtField.getText();

        String fullRepoPath = root.resolve(RepoName).toString();
        
        String gitUrl = CommandTxtField.getText();
        String Token = TokenTxtField.getText();

        GitServices git = new GitServices(fullRepoPath);

        SwingWorker<Void, Void> worker = new SwingWorker<>() {
            @Override
            protected Void doInBackground() throws Exception {

                ProgressMonitor monitor = new ProgressMonitor() {

                    private int totalTasks;
                    private int completedTasks;
                    private String compObject = "";
                    private int totalSubUnit;
                    private String titles;
                    private double Percentage;

                    @Override
                    public void start(int totalTasks) {
                        this.totalTasks = totalTasks;
                        this.completedTasks = 0;
                        GitProgressBar.setValue(this.completedTasks);
                        GitProgressBar.setStringPainted(true);
                    }

                    @Override
                    public void beginTask(String title, int totalWork) {
                        compObject = title; //name in progress bar

                        totalSubUnit = totalWork;
//                        System.out.println("Task: " + title + " (" + totalWork + " units)");
                        completedTasks = 0;

                        titles = title;

                    }

                    @Override
                    public void update(int completed) {

                        completedTasks += completed;

                        if (completedTasks != 0 && totalSubUnit != 0) {
                            Percentage = ((double) completedTasks / totalSubUnit) * 100;

                            javax.swing.SwingUtilities.invokeLater(() -> {
                                GitProgressBar.setValue((int) Percentage);
                                GitProgressBar.setString(titles);
                            });
                        }

//                        System.out.println("Progress: " + completedTasks + "/" + totalSubUnit);
//                        System.out.println((int) Percentage);
                    }

                    @Override
                    public void endTask() {
                    }

                    @Override
                    public boolean isCancelled() {
                        return false; // Return true if you want to cancel the operation
                    }

                    @Override
                    public void showDuration(boolean bln) {
                    }
                };

                try (Git result = Git.cloneRepository()
                        .setURI(gitUrl)
                        .setDirectory(new File(fullRepoPath))
                        .setProgressMonitor(monitor)
                        .setCredentialsProvider(new UsernamePasswordCredentialsProvider(Token, ""))
                        .call()) {

                    new DirectoryServices().GetDirectoryData(baseFrame.getJTable1());

                    java.awt.Window window = javax.swing.SwingUtilities.getWindowAncestor(CreateRepoPanel.this);
                    if (window != null) {
                        window.dispose();
                    }
                }
                return null;

            }

            @Override
            public void done() {
                try {
                    get(); // surfaces any exception thrown in doInBackground
                    GitProgressBar.setString("Clone Completed");
                    new DirectoryServices().GetDirectoryData(baseFrame.getJTable1());
                } catch (Exception ex) {
//                    ex.printStackTrace();
                    if (ex.getMessage().contains("git failed")) {
                        JOptionPane.showMessageDialog(jLabel1, "Error Cloning Git", "Error", JOptionPane.ERROR_MESSAGE);
                    } else {
                        JOptionPane.showMessageDialog(jLabel1, "Error" + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                        ex.printStackTrace();
                    }
                }
            }

        };

        worker.execute();
    }//GEN-LAST:event_jButton1ActionPerformed

